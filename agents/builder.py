"""
Jury Room slice 3 - Builder agent.

Reads a TASK from the Switch room, generates a unified diff via a model call,
runs the diff in a sandboxed Docker container, and posts results back to the room.
"""

import os
import subprocess
import tempfile
import shutil
import time
import re
from typing import Any

# Docker argv prefix for sandboxed test execution.
# "<dir>" is a literal placeholder replaced per run with the temp dir path.
SANDBOX_CMD: list[str] = [
    "docker", "run", "--rm", "--network", "none",
    "--cpus", "1", "--memory", "512m", "--pids-limit", "128",
    "--read-only", "--tmpfs", "/tmp",
    "-v", "<dir>:/w:ro", "-w", "/w",
    "python:3.12-slim", "python", "-B", "-m", "unittest", "discover",
    "-s", "/w", "-v"
]


def _parse_diff_files(diff: str) -> list[str]:
    """Extract sorted list of file paths from `+++ b/<path>` headers."""
    files = []
    for line in diff.splitlines():
        if line.startswith("+++ b/") and not line.startswith("+++ b//"):
            path = line[6:].strip()
            if path and path != "/dev/null":
                files.append(path)
    return sorted(set(files))


def _get_changed_files(repo_dir: str, temp_dir: str) -> list[str]:
    """
    Return sorted list of paths in temp_dir that differ from repo_dir.

    Files within any "__pycache__" directory are ignored, as they are
    artefacts generated by the test runner and should not affect diff/file
    integrity checks.
    """
    changed = []
    # Track files seen in temp_dir
    seen_in_temp = set()

    def _is_ignored(path: str) -> bool:
        # Ignore any path that has a __pycache__ component
        parts = path.split(os.sep)
        return "__pycache__" in parts

    for root, dirs, files in os.walk(temp_dir):
        dirs.sort()
        # Skip __pycache__ directories entirely
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        for f in sorted(files):
            temp_path = os.path.join(root, f)
            rel_path = os.path.relpath(temp_path, temp_dir)
            if _is_ignored(rel_path):
                continue
            seen_in_temp.add(rel_path)
            repo_path = os.path.join(repo_dir, rel_path)
            try:
                with open(temp_path, "rb") as tf:
                    temp_content = tf.read()
                if os.path.exists(repo_path):
                    with open(repo_path, "rb") as rf:
                        repo_content = rf.read()
                    if temp_content != repo_content:
                        changed.append(rel_path)
                else:
                    # File is new in temp_dir
                    changed.append(rel_path)
            except IOError:
                changed.append(rel_path)

    # Check for files deleted in temp_dir (ignore __pycache__ deletions)
    for root, dirs, files in os.walk(repo_dir):
        dirs.sort()
        dirs[:] = [d for d in dirs if d not in ("__pycache__", ".git")]  # .git is never copied to the sandbox
        for f in sorted(files):
            repo_path = os.path.join(root, f)
            rel_path = os.path.relpath(repo_path, repo_dir)
            if _is_ignored(rel_path):
                continue
            temp_path = os.path.join(temp_dir, rel_path)
            if not os.path.exists(temp_path):
                changed.append(rel_path)

    return sorted(set(changed))


def _read_python_files(repo_dir: str) -> str:
    """Read all *.py files from repo_dir and return them as a formatted string."""
    parts = []
    for root, dirs, files in os.walk(repo_dir):
        dirs.sort()
        for f in sorted(files):
            if f.endswith(".py"):
                path = os.path.join(root, f)
                rel_path = os.path.relpath(path, repo_dir)
                try:
                    with open(path, "r", encoding="utf-8") as fh:
                        content = fh.read()
                    parts.append(f"--- {rel_path} ---\n{content}")
                except (IOError, UnicodeDecodeError):
                    parts.append(f"--- {rel_path} ---\n(unreadable)")
    return "\n".join(parts)


def _strip_fences(text: str) -> str:
    """Remove markdown code fences from model output."""
    lines = text.splitlines()
    cleaned = []
    in_fence = False
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            continue
        if not in_fence:
            cleaned.append(line)
    return "\n".join(cleaned)


def run_sandbox(repo_dir: str, diff: str, timeout: int = 120) -> dict[str, Any]:
    """
    Apply a diff in a sandboxed temp copy of repo_dir and run tests.

    Copies the work tree of repo_dir (excluding .git) to a fresh temp dir,
    applies the given unified diff with `git apply --whitespace=nowarn`,
    enforces diff_files == changed_files, runs SANDBOX_CMD, and returns results.

    Args:
        repo_dir: Path to the repository directory (read-only, never modified).
        diff: Unified diff string (empty diff means no change, applied=True).
        timeout: Maximum seconds for the sandboxed test run.

    Returns:
        dict with keys:
            applied (bool): Whether the diff applied cleanly.
            returncode (int): Exit code of the test command (-1 if not run).
            passed (bool): True if applied and returncode == 0.
            output (str): Last 4000 characters of stdout+stderr.
            summary (str): "passed" or "failed" plus unittest result line.
            diff_files (list[str]): Sorted paths from `+++ b/<path>` headers.
            changed_files (list[str]): Sorted paths differing from repo_dir.

    Raises:
        FileNotFoundError: If repo_dir does not exist.
        subprocess.TimeoutExpired: If sandbox command exceeds timeout.
    """
    if not os.path.isdir(repo_dir):
        raise FileNotFoundError(f"Repository directory not found: {repo_dir}")

    diff_files = _parse_diff_files(diff)

    temp_dir = tempfile.mkdtemp(prefix="jr-sandbox-")
    try:
        # Copy work tree excluding .git
        for item in os.listdir(repo_dir):
            if item == ".git":
                continue
            src = os.path.join(repo_dir, item)
            dst = os.path.join(temp_dir, item)
            if os.path.isdir(src):
                shutil.copytree(src, dst, symlinks=True)
            else:
                shutil.copy2(src, dst)

        # Apply diff if non-empty
        applied = True
        if diff.strip():
            try:
                subprocess.run(
                    ["git", "apply", "--whitespace=nowarn"],
                    input=diff,
                    cwd=temp_dir,
                    capture_output=True,
                    text=True,
                    check=True,
                )
            except subprocess.CalledProcessError as e:
                return {
                    "applied": False,
                    "returncode": -1,
                    "passed": False,
                    "output": "",
                    "summary": f"failed: git apply failed: {e.stderr.strip()}",
                    "diff_files": diff_files,
                    "changed_files": [],
                }

        # Determine changed files after applying diff (ignore __pycache__)
        changed_files = _get_changed_files(repo_dir, temp_dir)

        # Integrity check
        if diff_files != changed_files:
            return {
                "applied": False,
                "returncode": -1,
                "passed": False,
                "output": "",
                "summary": "failed: diff file list mismatch",
                "diff_files": diff_files,
                "changed_files": changed_files,
            }

        # Build sandbox command
        cmd = [arg.replace("<dir>", temp_dir) for arg in SANDBOX_CMD]

        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        returncode = proc.returncode
        output = proc.stdout + "\n" + proc.stderr
        truncated_output = output[-4000:] if len(output) > 4000 else output

        passed = applied and returncode == 0

        # Extract unittest summary lines
        summary_lines = []
        for line in output.splitlines():
            stripped = line.strip()
            if re.search(r"Ran \d+ tests? in", stripped):
                summary_lines.append(stripped)
            elif stripped in ("OK", "FAILED (errors=0)", "FAILED (failures=1)",
                             "FAILED (failures=1, errors=0)"):
                summary_lines.append(stripped)

        if not summary_lines:
            summary_lines = ["OK"] if passed else [f"FAILED (returncode={returncode})"]

        summary = ("passed" if passed else "failed") + "\n" + "\n".join(summary_lines)

        return {
            "applied": applied,
            "returncode": returncode,
            "passed": passed,
            "output": truncated_output,
            "summary": summary,
            "diff_files": diff_files,
            "changed_files": changed_files,
        }

    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)


def run_builder(
    client: Any,
    room_id: str,
    repo_dir: str,
    model_call: Any,
    timeout: float = 90.0
) -> dict[str, Any]:
    """
    Read room for TASK, generate diff via model, sandbox-test it, and post CASE.

    Connects to the Switch room, reads history for the first message starting
    with "TASK:", builds a prompt containing the task and every *.py file in
    repo_dir verbatim, calls model_call(prompt) once for a unified diff, strips
    ``` fences, runs run_sandbox, and posts one message:
    `CASE: <task text>\nDIFF:\n<diff>\nTESTS: <summary>`.

    Args:
        client: Switch client instance (from agents/switch_client.py).
        room_id: Room name to connect to.
        repo_dir: Path to the repository directory.
        model_call: Callable that takes a prompt string and returns a string
                    containing a unified diff (possibly with ``` fences).
        timeout: Maximum seconds to wait for the TASK message.

    Returns:
        dict with keys:
            diff (str): The generated diff.
            sandbox (dict): Result from run_sandbox.
            posted (bool): True if the CASE message was posted successfully.

    Raises:
        TimeoutError: If no TASK message appears within timeout.
    """
    client.open_stream([room_id])
    client.connect_to_room(room_id)

    # Grab recent history to catch a pre-existing TASK
    try:
        history = client.call_op("read_context", {"limit": 50}, with_connection=True)
    except Exception:
        history = {"threads": []}

    task_body = None

    for thread in history.get("threads", []):
        root = thread.get("root", {})
        if root.get("kind") == "message" and isinstance(root.get("body"), str) and root["body"].startswith("TASK:"):
            task_body = root["body"]
            break
        for reply in thread.get("replies", []):
            if reply.get("kind") == "message" and isinstance(reply.get("body"), str) and reply["body"].startswith("TASK:"):
                task_body = reply["body"]
                break
        if task_body:
            break

    deadline = time.time() + timeout
    while task_body is None and time.time() < deadline:
        ev = client.next_event(timeout=2.0)
        if ev is None:
            client.beat()
            continue
        if ev.get("type") != "message":
            continue
        payload = ev.get("payload", {})
        body = str(payload.get("body", ""))
        if body.startswith("TASK:"):
            task_body = body
            break

    if task_body is None:
        raise TimeoutError("No TASK message received within timeout")

    # Preserve the exact text after the "TASK:" prefix (strip only the prefix)
    task_text = task_body[len("TASK:"):].lstrip()

    # Assemble source snapshot
    files_snapshot = _read_python_files(repo_dir)

    prompt = (
        "You are a Python developer. The user has described a task below.\n"
        "Here are the current Python files in the project:\n"
        f"{files_snapshot}\n\n"
        f"Task: {task_text}\n\n"
        "Generate a unified diff that implements the fix described in the task.\n"
        "Output ONLY the unified diff, with no additional explanation.\n"
        "The diff must be complete and ready for `git apply`.\n"
        "Use the format:\n"
        "--- a/<filename>\n"
        "+++ b/<filename>\n"
        "@@ -line,count +line,count @@\n"
        "...diff content..."
    )

    raw_reply = model_call(prompt)
    # Remove fences but keep the diff exactly as the model gave it
    diff_content = _strip_fences(raw_reply)
    # Ensure the diff ends with a newline for git apply
    if diff_content and not diff_content.endswith("\n"):
        diff_content += "\n"

    sandbox_result = run_sandbox(repo_dir, diff_content, timeout=120)

    # Embed the diff exactly as it will be applied, preserving its trailing newline
    case_msg = f"CASE: {task_text}\nDIFF:\n{diff_content}\nTESTS: {sandbox_result['summary']}"

    client.post_message(room_id, case_msg)

    return {
        "diff": diff_content,
        "sandbox": sandbox_result,
        "posted": True,
    }
